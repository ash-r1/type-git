// Independent Git oracle for callback languages; expected values never use Type-Git.
import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = new URL('../', import.meta.url);
const directory = await mkdtemp(join(tmpdir(), 'type-git-string-callbacks-'));
const env = { ...process.env, HOME: directory, XDG_CONFIG_HOME: directory, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_COUNT: '0', LC_ALL: 'C', GIT_PAGER: 'cat' };
for (const name of ['GIT_DIR', 'GIT_WORK_TREE', 'GIT_COMMON_DIR', 'GIT_INDEX_FILE', 'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES']) delete env[name];
function git(args) {
  const result = spawnSync('git', args, { cwd: directory, env, input: '', encoding: 'utf8', timeout: 60000 });
  if (result.error || result.signal) throw result.error ?? new Error(`Git terminated: ${result.signal}`);
  return result;
}
try {
  if (git(['--version']).stdout.trim() !== 'git version 2.55.0') throw new Error('The oracle requires Git 2.55.0');
  if (git(['init', '-q']).status !== 0) throw new Error('Cannot initialize native oracle repository');
  // Exhaust the bounded alphabet, including repeated separators and literal newlines.
  const maps = [''];
  let level = [''];
  for (let length = 1; length <= 4; length++) {
    level = level.flatMap(prefix => [':', 'x', '\n', '名', '-'].map(char => prefix + char));
    maps.push(...level);
  }
  maps.push('one:two:', 'one:two:three', ' ', ' : ', '-h', 'a'.repeat(256), `${'a'.repeat(256)}:`);
  const names = ['abort', 'verbatim', 'ignore', 'warn-verbatim', 'warn', 'warn-strip', 'strip', 'abort-if-invalid', 'strip-if-invalid', 'sign-if-invalid'];
  const signs = [...new Set(['', '-h', 'sign-if-invalid=', 'sign-if-invalid=key', 'sign-if-invalid==', 'sign-if-invalid=\n', 'sign-if-invalid=鍵:tag', 'sign-if-invalid= ', 'sign-if-invalid=--help', ...names.flatMap(name => [name, name.toUpperCase(), ` ${name}`, `${name} `, `${name}\n`, `${name}=`, `${name}=key`, name.slice(0, -1)])])];
  const cases = [];
  for (const [command, flag, parser, values] of [
    ['fast-export', '--anonymize-map', 'anonymize-map', maps],
    ['fast-import', '--signed-tags', 'fast-import-sign', signs],
    ['fast-import', '--signed-commits', 'fast-import-sign', signs],
  ]) for (const value of values) {
    const tokens = command === 'fast-export' ? [[flag, value], ['-h']] : [['--quiet'], [flag, value]];
    const argv = [command, ...tokens.map(([name, arg]) => arg === undefined ? name : `${name}=${arg}`)];
    const result = git(argv);
    const valid = command === 'fast-import' ? result.status === 0 : result.status === 129 && (result.stderr + result.stdout).startsWith('usage:');
    const invalid = result.status === 129 && (command === 'fast-import' ? result.stderr.startsWith(`usage: unknown ${flag} mode`) : result.stderr.startsWith('error:'));
    if (!valid && !invalid) throw new Error(`Unclassified ${JSON.stringify(argv)}: ${result.status}: ${result.stdout}${result.stderr}`);
    cases.push({ command, flag, parser, value, tokens, argv, valid });
  }
  const fixture = JSON.stringify({ profile: 'Git 2.55.0, LC_ALL=C; empty fast-import stdin; fast-export callback before initial-pass help', cases }, null, 2) + '\n';
  // Long numeric/string walks deliberately defer at the compiler's budget boundary.
  const types = `// Generated by node scripts/string-callback-corpus.mjs from independent Git outcomes.\nimport type { CheckedCommandArguments, GitCommandArgument, GitCommandName } from '../../src/commands/types.js';\nimport type { StringCallbackLiteral } from '../../src/constraints/string-callback-types.js';\ntype Check<T extends true> = T;\ntype Accepted<C extends GitCommandName, A extends readonly GitCommandArgument<C>[]> = [CheckedCommandArguments<C, A>] extends [never] ? false : true;\nexport type NativeStringCallbackCases = readonly [\n` + cases.filter(row => row.value.length < 128).map(row => `  Check<StringCallbackLiteral<${JSON.stringify(row.value)}, ${JSON.stringify(row.parser)}> extends ${row.valid} ? true : false>, Check<Accepted<${JSON.stringify(row.command)}, ${JSON.stringify(row.tokens)}> extends ${row.valid} ? true : false>,`).join('\n') + '\n];\n';
  for (const [path, content] of [['test/fixtures/string-callback-corpus.json', fixture], ['test/types/string-callback-corpus.ts', types]]) {
    const target = new URL(path, root);
    if (process.argv.includes('--check')) {
      if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error(`${path} is stale`);
    } else await writeFile(target, content);
  }
  console.log(`Generated/checked ${cases.length} native string callback outcomes (${cases.filter(row => row.value.length < 128).length} within compiler budget).`);
} finally { await rm(directory, { recursive: true, force: true }); }
