// Independent Git oracle for the reset guaranteed path arity.
import { oracleEnv, gitRunner, serialize } from './checkout-oracle.mjs';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = new URL('../', import.meta.url);
const directory = await mkdtemp(join(tmpdir(), 'type-git-reset-path-arity-'));
const git = gitRunner(directory, oracleEnv(directory));
/** Keep literal native words independent of production validation. */
const operand = value => ({ operand: value });

try {
  await writeFile(join(directory, 'oracle-input'), 'file\n');
  await writeFile(join(directory, 'oracle-input-nul'), 'file\0');
  if (git(['--version']).stdout.trim() !== 'git version 2.55.0') throw new Error('The oracle requires Git 2.55.0');
  if (git(['init', '-qb', 'main']).status !== 0) throw new Error('Cannot initialize oracle');
  for (const path of ['file', 'other', '--']) await writeFile(join(directory, path), 'one\n');
  for (const args of [['add', '--', '.'], ['commit', '-qm', 'seed'], ['commit', '--allow-empty', '-qm', 'second']]) if (git(args).status !== 0) throw new Error('Cannot seed oracle');
  const cases = [];
  const sequences = [];
  for (const mode of ['--hard', '--soft', '--merge', '--keep', '--mixed']) {
    for (const words of [[operand('HEAD')], [operand('HEAD'), operand('file')], [operand('file'), operand('other')], [operand('HEAD'), operand('HEAD~1'), ['--'], operand('file')], [operand('HEAD'), ['--']], [operand('HEAD'), ['--'], operand('file')]]) sequences.push([[mode], ...words]);
    sequences.push([[mode], operand('HEAD'), operand('file'), ['-h']]);
  }
  for (const words of [[], [operand('HEAD')], [operand('HEAD'), operand('file')], [operand('HEAD'), operand('HEAD~1'), ['--'], operand('file')], [['--'], operand('file')]]) sequences.push([['--pathspec-from-file', '-'], ...words]);
  for (const tokens of sequences) {
    const argv = ['reset', ...serialize(tokens)];
    const result = git(argv);
    const valid = result.status === 0 || (result.status === 129 && result.stdout.startsWith('usage:') && !result.stderr);
    if (![0, 1, 128, 129].includes(result.status)) throw new Error(`Unclassified native reset: ${JSON.stringify(argv)} ${result.status}`);
    cases.push({ command: 'reset', tokens, argv, valid, status: result.status, diagnostic: result.stderr.split('\n')[0] });
  }
  const fixture = JSON.stringify({ profile: 'Git 2.55.0; fixed dates and clean repository; at most one retained word can be a revision; recognized separators, mode restrictions and pathspec-file boundaries; no user repository access', cases }, null, 2) + '\n';
  const types = `// Generated by node scripts/reset-path-arity-corpus.mjs from independent native outcomes.\nimport type { CheckedCommandArguments, GitCommandArgument } from '../../src/commands/types.js';\ntype Check<T extends true> = T;\ntype Accepted<A extends readonly GitCommandArgument<'reset'>[]> = [CheckedCommandArguments<'reset', A, { integerProfile: 'bounded'; firstPassEmpty: true; booleanSource: 'modern'; conflictStyle: 'immediate'; decimalCallbacks: { 'unified-context': 'modern'; 'revision-count': 'modern'; 'strip-count': 'modern'; 'daemon-count': 'modern'; 'daemon-timeout': 'modern'; 'daemon-init-timeout': 'modern' } }>] extends [never] ? false : true;\nexport type NativeResetPathArity = readonly [\n` + cases.map(row => `  Check<Accepted<${JSON.stringify(row.tokens)}> extends ${row.valid} ? true : false>,`).join('\n') + '\n];\n';
  for (const [path, content] of [['test/fixtures/reset-path-arity-corpus.json', fixture], ['test/types/reset-path-arity-corpus.ts', types]]) {
    const target = new URL(path, root);
    if (process.argv.includes('--check')) { if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error(`${path} is stale`); }
    else await writeFile(target, content);
  }
  console.log(`Generated/checked ${cases.length} independent reset path arity outcomes.`);
} finally { await rm(directory, { recursive: true, force: true }); }
