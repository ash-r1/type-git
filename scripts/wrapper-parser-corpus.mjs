// Independent native oracle for the ordered reflog wrapper, log and revision passes.
import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = new URL('../', import.meta.url);
const directory = await mkdtemp(join(tmpdir(), 'type-git-wrapper-oracle-'));
const env = { ...process.env, HOME: directory, XDG_CONFIG_HOME: directory, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_COUNT: '0', LC_ALL: 'C', GIT_PAGER: 'cat', GIT_AUTHOR_NAME: 'Test', GIT_AUTHOR_EMAIL: 'test@example.test', GIT_COMMITTER_NAME: 'Test', GIT_COMMITTER_EMAIL: 'test@example.test' };
for (const name of ['GIT_DIR', 'GIT_WORK_TREE', 'GIT_COMMON_DIR', 'GIT_INDEX_FILE', 'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES']) delete env[name];
function git(args) {
  const result = spawnSync('git', args, { cwd: directory, env, input: '', encoding: 'utf8', timeout: 60000 });
  if (result.error || result.signal) throw result.error ?? new Error(`Git terminated: ${result.signal}`);
  return result;
}
const operand = value => ({ operand: value });
const count = ['--max-count', '0'];
try {
  if (git(['--version']).stdout.trim() !== 'git version 2.55.0') throw new Error('The oracle requires Git 2.55.0');
  if (git(['init', '-q']).status !== 0) throw new Error('Cannot initialize oracle repository');
  await writeFile(join(directory, 'file'), 'x\ny\n');
  if (git(['add', 'file']).status !== 0 || git(['commit', '-qm', 'seed']).status !== 0) throw new Error('Cannot seed oracle repository');
  const cases = [];
  const record = (command, tokens) => {
    const argv = [...command.split(' '), ...tokens.flatMap(token => !Array.isArray(token) ? [token.operand] : token.length === 1 ? token : token[0].startsWith('--') && token[0] !== '--default' ? [`${token[0]}=${token[1]}`] : token)];
    const result = git(argv);
    const text = result.stderr + result.stdout;
    const valid = result.status === 0 || (result.status === 129 && text.startsWith('usage:'));
    const invalid = (result.status === 129 && result.stderr.startsWith('error:')) || (result.status === 128 && /^(fatal|error):/.test(result.stderr));
    if (!valid && !invalid) throw new Error(`Unclassified ${JSON.stringify(argv)}: ${result.status}: ${text}`);
    cases.push({ command, tokens, argv, valid, status: result.status, diagnostic: (result.status === 0 ? result.stderr : text).split('\n')[0] });
  };
  for (const command of ['reflog', 'reflog show']) {
    const sequences = [[], [count], [['--color', 'bad']], [['--decorate', 'bad']],
      [['--graph']], [['--reverse']], [['--reverse'], ['--reverse']],
      [['--'], ['--color', 'bad']], [count, ['--'], ['--color', 'bad']],
      [['-G', '-L'], ['-h']], [['--default', '-L'], ['-h']],
      [['--default', '--decorate=bad'], operand('HEAD')],
      [['--default', '--decorate'], operand('HEAD')],
      [operand('--end-of-options'), operand('HEAD')],
    ];
    const upstream = JSON.parse(await readFile(new URL('spec/upstream/git-option-tables.json', root), 'utf8'));
    const wrapper = upstream.files.find(file => file.file === 'builtin/reflog.c').tables.find(table => table.function === 'cmd_reflog');
    for (const name of wrapper.options.map(option => option.long).filter(Boolean)) {
      for (let size = 1; size <= name.length; size++) sequences.push([operand(`-${name.slice(0, size)}`), ['-h']]);
    }
    const before = [['--decorate', 'bad'], ['--color', 'bad'], ['--graph'], ['--max-count', 'bad']];
    const helps = [['-h'], ['--help'], operand('--help-all')];
    for (const early of before) for (const help of helps) {
      sequences.push([early, help], [help, early], [operand('HEAD'), early, help]);
    }
    for (const value of ['-h', '--help', '--help-all', '--decorate=bad', '--decorate', '-L', '-qh', '-xqh', '-no-color', '--help=bad', '--', '--end-of-options']) {
      for (const flag of ['-G', '--default', '-n']) sequences.push([[flag, value], ['-h']]);
    }
    for (const value of ['', 'true', 'TRUE', 'false', '0', '-1', '2147483648', 'short', 'full', 'auto', 'bad']) {
      sequences.push([['--decorate', value]], [['--decorate', value], ['-h']]);
    }
    for (const tokens of sequences) {
      // Leading --help of the root command is the separate global dispatcher.
      if (command === 'reflog' && tokens[0]?.[0] === '--help') continue;
      record(command, tokens);
      if (command === 'reflog show') record('reflog', [operand('show'), ...tokens]);
    }
  }
  const fixture = JSON.stringify({ profile: 'Git 2.55.0; seeded repository; ordered reflog wrappers, log and revision parsers; no user repository access', cases }, null, 2) + '\n';
  const types = `// Generated by node scripts/wrapper-parser-corpus.mjs from independent Git outcomes.\nimport type { CheckedCommandArguments, GitCommandArgument, GitCommandName } from '../../src/commands/types.js';\ntype Check<T extends true> = T;\ntype Accepted<C extends GitCommandName, A extends readonly GitCommandArgument<C>[]> = [CheckedCommandArguments<C, A>] extends [never] ? false : true;\nexport type NativeWrapperParserCases = readonly [\n` + cases.map(row => `  Check<Accepted<${JSON.stringify(row.command)}, ${JSON.stringify(row.tokens)}> extends ${row.valid} ? true : false>,`).join('\n') + '\n];\n';
  for (const [path, content] of [['test/fixtures/wrapper-parser-corpus.json', fixture], ['test/types/wrapper-parser-corpus.ts', types]]) {
    const target = new URL(path, root);
    if (process.argv.includes('--check')) {
      if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error(`${path} is stale`);
    } else await writeFile(target, content);
  }
  console.log(`Generated/checked ${cases.length} independent wrapper parser outcomes.`);
} finally { await rm(directory, { recursive: true, force: true }); }
