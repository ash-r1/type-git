import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const registry = JSON.parse(await readFile(new URL('spec/git-compound-decimals.json', root), 'utf8'));
for (const [name, profile] of Object.entries(registry.profiles)) {
  if (!profile.source || profile.separator !== ',') throw new Error(`Invalid compound profile: ${name}`);
  if (profile.kind === 'tuple') {
    if (!profile.defaults.length || !profile.defaults.every(Number.isSafeInteger)) throw new Error(`${name}: invalid defaults`);
    for (const index of [profile.nonzeroGreaterThan.index, ...profile.nonzeroGreaterThan.others]) if (!Number.isInteger(index) || index < 0 || index >= profile.defaults.length) throw new Error(`${name}: invalid relation index`);
  } else if (profile.kind !== 'prefix') throw new Error(`${name}: unknown compound parser`);
}
const source = `// Generated by node scripts/compound-decimals.mjs. Do not edit.\nimport type { CompoundDecimalProfile } from './compound-decimal.js';\nexport const COMPOUND_DECIMALS = ${JSON.stringify(registry.profiles, null, 2)} as const satisfies Record<string, CompoundDecimalProfile>;\n`;
const result = spawnSync(process.execPath, [require.resolve('@biomejs/biome/bin/biome'), 'format', '--stdin-file-path=src/constraints/compound-decimals.generated.ts'], { input: source, encoding: 'utf8' });
if (result.status !== 0) throw new Error(result.stderr);
const target = new URL('src/constraints/compound-decimals.generated.ts', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== result.stdout) throw new Error('Compound decimal profiles are stale');
} else await writeFile(target, result.stdout);
