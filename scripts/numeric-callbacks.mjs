import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const registry = JSON.parse(await readFile(new URL('spec/git-numeric-callbacks.json', root), 'utf8'));
const parsers = Object.fromEntries(Object.entries(registry.profiles).map(([name, profile]) => [name, profile.parser]));
const source = `// Generated by node scripts/numeric-callbacks.mjs. Do not edit.\nimport type { GitScalarParser } from './git-scalars.js';\nexport const NUMERIC_CALLBACK_PARSERS = ${JSON.stringify(parsers, null, 2)} as const satisfies Record<string, GitScalarParser>;\n`;
const result = spawnSync(process.execPath, [require.resolve('@biomejs/biome/bin/biome'), 'format', '--stdin-file-path=src/constraints/numeric-callbacks.generated.ts'], { input: source, encoding: 'utf8' });
if (result.status !== 0) throw new Error(result.stderr);
const target = new URL('src/constraints/numeric-callbacks.generated.ts', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== result.stdout) throw new Error('Numeric callback rules are stale');
} else await writeFile(target, result.stdout);
