// Git url_percent_decode maps nonzero byte escapes and preserves %00/malformed escapes.
import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const bytes = Object.fromEntries(Array.from({ length: 255 }, (_, i) => [(i + 1).toString(16).padStart(2, '0'), String.fromCharCode(i + 1)]));
const controls = Array.from({ length: 33 }, (_, i) => JSON.stringify(String.fromCharCode(i))).join(' | ');
const source = '// Generated by node scripts/url-byte-types.mjs. Do not edit.\nexport type UrlBytes = ' + JSON.stringify(bytes) + ';\nexport type ReservedControl = ' + controls + ';\n';
const formatted = spawnSync(process.execPath, [require.resolve('@biomejs/biome/bin/biome'), 'format', '--stdin-file-path=src/constraints/url-byte-types.ts'], { input: source, encoding: 'utf8' });
if (formatted.status !== 0) throw new Error(formatted.stderr);
const target = new URL('../src/constraints/url-byte-types.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== formatted.stdout) throw new Error('URL byte types are stale');
} else await writeFile(target, formatted.stdout);
