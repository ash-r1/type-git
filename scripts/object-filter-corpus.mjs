// Independent Git oracle for byte decoding and unsigned-long literal boundaries.
// Run with Git 2.55.0 on the pinned LP64, unsigned-char profile.
import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const version = spawnSync('git', ['--version'], { encoding: 'utf8' }).stdout.trim();
if (version !== 'git version 2.55.0') throw new Error(`Expected pinned Git 2.55.0, got ${version}`);
const root = new URL('../', import.meta.url);
const temp = await mkdtemp(join(tmpdir(), 'type-git-filter-corpus-'));
try {
  const env = { ...process.env, HOME: temp, XDG_CONFIG_HOME: temp, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: join(temp, 'config'), LC_ALL: 'C' };
  if (spawnSync('git', ['init', temp], { env }).status !== 0) throw new Error('Fixture init failed');
  const samples = new Set();
  for (let byte = 0; byte < 256; byte++) {
    const escaped = `%${byte.toString(16).padStart(2, '0')}`;
    for (const spelling of [escaped, escaped.toUpperCase()]) {
      for (const prefix of ['combine:tree:', 'combine:sparse:oid=', 'combine:combine:sparse:oid=']) samples.add(prefix + spelling);
    }
  }
  for (let byte = 1; byte <= 32; byte++) samples.add(`combine:sparse:oid=${String.fromCharCode(byte)}`);
  const numbers = ['18446744073709551615', '18446744073709551616', '0xffffffffffffffff', '0x10000000000000000', '01777777777777777777777', '02000000000000000000000', `0b${'1'.repeat(64)}`, `0b1${'0'.repeat(64)}`, '18014398509481983k', '18014398509481984k', '17592186044415m', '17592186044416m', '17179869183g', '17179869184g', '+001', '-0', '1\n'];
  for (const number of numbers) for (const prefix of ['blob:limit=', 'tree:', 'combine:tree:']) samples.add(prefix + number);
  for (const sample of ['combine:tree:%31', 'combine:tree:%2b1', 'combine:tree:%201', 'combine:tree:1844674407370955161%36', 'combine:combine:tree:1%2Bauto', 'combine:combine:tree:1%252Bauto', 'combine:sparse:oid=%', 'combine:sparse:oid=%0', 'combine:sparse:oid=%xx', 'combine:unknown%xx', 'combine:tree:%2%31', 'combine:combine:sparse:oid=%2520', 'combine:combine:sparse:oid=%20', 'combine:combine:sparse:oid=%252520']) samples.add(sample);
  const cases = [...samples].map(filter => {
    const result = spawnSync('git', ['-C', temp, 'cat-file', `--filter=${filter}`, '-h'], { env, encoding: 'utf8', timeout: 5000 });
    if (result.error) throw result.error;
    const valid = result.status === 129 && (result.stdout + result.stderr).includes('usage:');
    if (!valid && (result.status !== 128 || !result.stderr.includes('fatal:'))) throw new Error(`Unexpected result for ${JSON.stringify(filter)}: ${result.stderr}`);
    return { filter, valid };
  });
  if (!cases.find(row => row.filter === 'blob:limit=18446744073709551615')?.valid || !cases.find(row => row.filter === 'combine:combine:sparse:oid=%ff')?.valid) throw new Error('Expected LP64 / unsigned-char native profile');
  const corpus = JSON.stringify({ profile: 'Git 2.55.0, LP64, unsigned char; cat-file filter callback before help', cases }, null, 2) + '\n';
  const types = '// Generated by node scripts/object-filter-corpus.mjs from independent Git executions.\nimport type { ObjectFilterLiteral } from "../../src/constraints/object-filter-types.js";\ntype Check<T extends true> = T;\nexport type Corpus = [\n' + cases.map(({ filter, valid }) => `  Check<ObjectFilterLiteral<${JSON.stringify(filter)}> extends ${valid} ? true : false>`).join(',\n') + '\n];\n';
  await mkdir(new URL('test/fixtures/', root), { recursive: true });
  for (const [path, content] of [['test/fixtures/object-filter-corpus.json', corpus], ['test/types/object-filter-byte-corpus.ts', types]]) {
    const target = new URL(path, root);
    if (process.argv.includes('--check')) {
      if (await readFile(target, 'utf8') !== content) throw new Error(`${path} is stale`);
    } else await writeFile(target, content);
  }
  console.log(`Verified ${cases.length} independent Git filter results.`);
} finally { await rm(temp, { recursive: true, force: true }); }
