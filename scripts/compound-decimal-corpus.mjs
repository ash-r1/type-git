// Independent Git outcomes for strtoul compound callbacks; no Type-Git parser is used.
import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = new URL('../', import.meta.url);
const directory = await mkdtemp(join(tmpdir(), 'type-git-compound-corpus-'));
const env = { ...process.env, HOME: directory, XDG_CONFIG_HOME: directory, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_COUNT: '0', LC_ALL: 'C', GIT_PAGER: 'cat' };
for (const name of ['GIT_DIR', 'GIT_WORK_TREE', 'GIT_COMMON_DIR', 'GIT_INDEX_FILE', 'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES']) delete env[name];
function git(args) {
  const result = spawnSync('git', args, { cwd: directory, env, encoding: 'utf8', timeout: 60000 });
  if (result.error || result.signal) throw result.error ?? new Error(`Git terminated: ${result.signal}`);
  return result;
}
try {
  if (git(['--version']).stdout.trim() !== 'git version 2.55.0') throw new Error('The oracle requires Git 2.55.0');
  if (git(['init', '-q']).status !== 0) throw new Error('Cannot initialize native oracle repository');
  const spelling = ['', '0', '-0', '+0', '1', '-1', '010', '08', '0x10', '0b1', '1k', '2147483647', '2147483648', '-2147483648', '4294967296', '9223372036854775808', '18446744073709551615', '18446744073709551616', '18446744073709551617', '-18446744073709551615', '-18446744073709551540', '-18446744071562067969', '-18446744071562067968', '-18446744073709551616', '-18446744073709551617', '99999999999999999999999999999999999999999999999999', '-99999999999999999999999999999999999999999999999999', ' 76', '\t76', '\n76', '76 ', '76\n', '76\r', '76\r\n', '76\u2028', '76\u2029', '', ' ', '\n', '+', '-', 'invalid'];
  const wrap = new Set(['', ',', ',,', ',,,', '76,6,9,', '76,6,9\n']);
  const small = ['', '0', '1', '6', '9', '10', '76', '2147483647'];
  for (const width of small) for (const first of small) for (const rest of small) wrap.add(`${width},${first},${rest}`);
  for (const value of spelling) for (const tuple of [value, `${value},0,0`, `76,${value},0`, `76,0,${value}`]) wrap.add(tuple);
  const reflog = new Set(spelling.flatMap(value => [value, `${value},date`, `${value},date\n`, `${value},`, `${value},,`]));
  const cases = [];
  for (const [parser, command, flag, values] of [['shortlog-wrap', 'shortlog', '-w', wrap], ['show-branch-reflog', 'show-branch', '--reflog', reflog]]) {
    for (const value of values) {
      const argv = [command, flag.startsWith('--') ? `${flag}=${value}` : `${flag}${value}`, '-h'];
      const result = git(argv);
      const valid = result.status === 129 && (result.stderr + result.stdout).startsWith('usage:');
      const invalid = result.status === 129 && result.stderr.startsWith('error:');
      if (!valid && !invalid) throw new Error(`Unclassified compound ${JSON.stringify(argv)}: ${result.status}: ${result.stdout}${result.stderr}`);
      cases.push({ parser, command, flag, value, valid });
    }
  }
  for (const [value, valid] of [['-18446744073709551540', true], ['-18446744073709551616', false]]) {
    if (cases.find(row => row.parser === 'shortlog-wrap' && row.value === value)?.valid !== valid) throw new Error('Native unsigned-long profile differs from LP64');
  }
  const exits = [];
  for (const tokens of [
    [['-h'], ['-w', '76\n']], [['-w', '76\n'], ['-h']],
    [['--color', 'invalid'], ['-h']], [['-h'], ['--color', 'invalid']],
    [['--color', 'AUTO'], ['-h']], [['--no-color'], ['-h']],
    [['-w', '-18446744073709551540'], ['--color', 'auto'], ['-h']],
  ]) {
    const argv = ['shortlog', ...tokens.map(([flag, value]) => value === undefined ? flag : flag.startsWith('--') ? `${flag}=${value}` : `${flag}${value}`)];
    const result = git(argv);
    const valid = result.status === 129 && (result.stderr + result.stdout).startsWith('usage:');
    if (!valid && !(result.status === 129 && result.stderr.startsWith('error:'))) throw new Error(`Unclassified exit: ${JSON.stringify(argv)}`);
    exits.push({ tokens, argv, valid });
  }
  const fixture = JSON.stringify({ profile: 'Git 2.55.0; LP64 strtoul saturation, unsigned negation and 32-bit int storage; LC_ALL=C', cases, exits }, null, 2) + '\n';
  const types = `// Generated by node scripts/compound-decimal-corpus.mjs from independent Git outcomes.\nimport type { CompoundDecimalLiteral } from '../../src/constraints/compound-decimal-types.js';\nimport type { Git } from '../../src/core/git.js';\ntype Check<T extends true> = T;\nexport type NativeCompoundCases = readonly [\n` + cases.map(row => `  Check<CompoundDecimalLiteral<${JSON.stringify(row.value)}, ${JSON.stringify(row.parser)}> extends ${row.valid} ? true : false>,`).join('\n') + '\n];\ndeclare const git: Git;\n' + exits.map(row => `${row.valid ? '' : '// @ts-expect-error Native Git rejects a reached callback before help.\n'}git.command('shortlog', ${JSON.stringify(row.tokens)});`).join('\n') + '\n';
  for (const [path, content] of [['test/fixtures/compound-decimal-corpus.json', fixture], ['test/types/compound-decimal-corpus.ts', types]]) {
    const target = new URL(path, root);
    if (process.argv.includes('--check')) {
      if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error(`${path} is stale`);
    } else await writeFile(target, content);
  }
  console.log(`Generated/checked ${cases.length} independent compound decimal cases and ${exits.length} ordered exit cases.`);
} finally { await rm(directory, { recursive: true, force: true }); }
