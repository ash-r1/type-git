// Independent Git oracle: expected outcomes never call the Type-Git validator.
import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = new URL('../', import.meta.url);
const directory = await mkdtemp(join(tmpdir(), 'type-git-parser-exits-'));
const env = { ...process.env, HOME: directory, XDG_CONFIG_HOME: directory, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null', LC_ALL: 'C', GIT_PAGER: 'cat', GIT_CONFIG_COUNT: '0' };
for (const name of ['GIT_DIR', 'GIT_WORK_TREE', 'GIT_COMMON_DIR', 'GIT_INDEX_FILE', 'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES']) delete env[name];
function git(args) {
  const result = spawnSync('git', args, { cwd: directory, env, encoding: 'utf8', timeout: 60000 });
  if (result.error || result.signal) throw result.error ?? new Error(`Git terminated: ${result.signal}`);
  return result;
}
try {
  if (git(['--version']).stdout.trim() !== 'git version 2.55.0') throw new Error('The oracle requires Git 2.55.0');
  if (git(['init', '-q']).status !== 0) throw new Error('Cannot initialize native oracle repository');
  const values = ['always', 'aLwAyS', 'auto', 'AUTO', 'never', 'NeVeR', 'true', 'yes', 'on', 'false', 'no', 'off', '', '0', '1', 'automatic', 'always ', ' never', 'ALWＡYS', '-h'];
  const sequences = values.flatMap(value => [[['--color', value], ['-h']], [['-h'], ['--color', value]]]);
  sequences.push(
    [['--color'], ['-h']], [['--no-color'], ['-h']],
    [['--color', 'invalid'], ['--color', 'always'], ['-h']],
    [['--color', 'always'], ['--color', 'invalid'], ['-h']],
    [['-h'], ['--color', 'invalid'], ['--color', 'always']],
    [['--no-color'], ['--help'], ['--color', 'invalid']],
    [['--color', 'invalid'], ['--help']],
    [['--color', 'auto'], ['--help']],
    [['-h'], ['--'], ['--'], ['--color', 'invalid']],
  );
  const other = {
    add: [['--chmod', 'bad']], rm: [['--force']], mv: [['--force']],
    commit: [['--cleanup', 'bad']], fetch: [['--filter', 'bad']],
    push: [['--force']], clone: [['--filter', 'bad']], merge: [['--log', 'bad']],
    reset: [['--soft'], ['--hard']], clean: [['--exclude', 'foo']],
    rebase: [['--empty', 'bad']], checkout: [['--unified', 'bad']],
    switch: [['--conflict', 'bad']], restore: [['--unified', 'bad']],
    status: [['--untracked-files', 'bad']],
  };
  const cases = [];
  for (const command of ['branch', 'for-each-ref', 'tag', 'show-branch', ...Object.keys(other)]) {
    const extra = command === 'branch' ? [
      [['--track', 'invalid'], ['-h']], [['-h'], ['--track', 'invalid']],
    ] : command === 'for-each-ref' ? [
      [['--count', 'garbage'], ['-h']], [['-h'], ['--count', 'garbage']],
    ] : command === 'tag' ? [
      [['-h'], ['--delete'], ['--verify']],
    ] : [[['-h'], ['--more', 'bad']]];
    const commandSequences = other[command] ? [
      [...other[command], ['-h']], [['-h'], ...other[command]], [['-h'], ['--'], ['--']],
    ] : [...sequences, ...extra];
    for (const tokens of commandSequences) {
      const argv = [command, ...tokens.map(([flag, value]) => value === undefined ? flag : `${flag}=${value}`)];
      const result = git(argv);
      const valid = result.status === 129 && (result.stderr + result.stdout).startsWith('usage:');
      const invalid = (result.status === 129 && result.stderr.startsWith('error:')) || (result.status === 128 && result.stderr.startsWith('fatal:'));
      if (!valid && !invalid) throw new Error(`Unclassified native outcome ${JSON.stringify(argv)}: ${result.status}: ${result.stdout}${result.stderr}`);
      cases.push({ command, tokens, argv, valid, status: result.status, diagnostic: (result.stderr + result.stdout).split('\n')[0] });
    }
  }
  const fixture = JSON.stringify({ profile: 'Git 2.55.0, LC_ALL=C; ordinary single-pass parse-options help exits', cases }, null, 2) + '\n';
  const types = `// Generated by node scripts/parser-exit-corpus.mjs from independent Git outcomes.\nimport type { CheckedCommandArguments, GitCommandArgument, GitCommandName } from '../../src/commands/types.js';\ntype Check<T extends true> = T;\ntype Accepted<C extends GitCommandName, A extends readonly GitCommandArgument<C>[]> = [CheckedCommandArguments<C, A>] extends [never] ? false : true;\nexport type NativeParserExitCases = readonly [\n` + cases.map(row => `  Check<Accepted<${JSON.stringify(row.command)}, ${JSON.stringify(row.tokens)}> extends ${row.valid} ? true : false>,`).join('\n') + '\n];\n';
  for (const [path, content] of [['test/fixtures/parser-exit-corpus.json', fixture], ['test/types/parser-exit-corpus.ts', types]]) {
    const target = new URL(path, root);
    if (process.argv.includes('--check')) {
      if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error(`${path} is stale`);
    } else await writeFile(target, content);
  }
  console.log(`Generated/checked ${cases.length} independent parser-exit outcomes.`);
} finally { await rm(directory, { recursive: true, force: true }); }
