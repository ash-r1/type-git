// Small multiplication tables make literal normalization independent of compiler arithmetic.
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
import { readFile, writeFile } from 'node:fs/promises';
const target = new URL('../src/constraints/integer-type-tables.ts', import.meta.url);
const products = Object.fromEntries([2, 8, 10, 16].map(base => [base,
  Object.fromEntries(Array.from({ length: 10 }, (_, digit) => [digit,
    Array.from({ length: base }, (_, carry) => [String(Math.floor((digit * base + carry) / 10)), String((digit * base + carry) % 10)])]))]));
const limits = Object.fromEntries([8, 16, 32, 64].map(bits => [bits, { signed: String(2n ** BigInt(bits - 1) - 1n), negative: String(2n ** BigInt(bits - 1)), unsigned: String(2n ** BigInt(bits) - 1n) }]));
const differences = Object.fromEntries(Array.from({ length: 10 }, (_, left) => [left,
  Object.fromEntries(Array.from({ length: 10 }, (_, right) => [right,
    [0, 1].map(borrow => [left - right - borrow < 0 ? '1' : '0', String((left - right - borrow + 10) % 10)])]))]));
const unformatted = '// Generated by node scripts/integer-type-tables.mjs. Do not edit.\nexport type IntegerProducts = ' + JSON.stringify(products) + ';\nexport type IntegerLimits = ' + JSON.stringify(limits) + ';\nexport type IntegerDifferences = ' + JSON.stringify(differences) + ';\n';
const formatted = spawnSync(process.execPath, [require.resolve('@biomejs/biome/bin/biome'), 'format', '--stdin-file-path=src/constraints/integer-type-tables.ts'], { input: unformatted, encoding: 'utf8' });
if (formatted.status !== 0) throw new Error(formatted.stderr);
const content = formatted.stdout;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== content) throw new Error('Integer type tables are stale');
} else await writeFile(target, content);
