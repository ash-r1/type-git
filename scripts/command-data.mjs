// Compact runtime encoding for the generated command catalogue.
//
// The literal catalogue in src/commands/generated.ts is the type-level source of
// truth. Runtime code instead decodes this JSON text on first use, which keeps the
// bundled value small and avoids evaluating a multi-megabyte object literal at
// import time. Repeated subtrees are stored once in a table and referenced as
// {"@": index}; src/commands/catalogue.ts resolves those references.

const REFERENCE = '@';
// A reference costs about as much as a short subtree, so only hoist larger ones.
const MINIMUM_SHARED_LENGTH = 12;

/** Encode a JSON-compatible catalogue as [sharedTable, root] with subtree references. */
export function encodeCommandData(catalog) {
  const counts = new Map();
  (function count(node) {
    if (!node || typeof node !== 'object') return;
    if (!Array.isArray(node)) {
      for (const key of [REFERENCE, '__proto__']) {
        if (Object.hasOwn(node, key)) throw new Error(`Command data cannot encode key ${key}`);
      }
    }
    const json = JSON.stringify(node);
    counts.set(json, (counts.get(json) ?? 0) + 1);
    for (const child of Object.values(node)) count(child);
  })(catalog);
  // Children serialize strictly shorter than parents, so this order lets the
  // decoder resolve each table entry from entries that precede it.
  const shared = [...counts]
    .filter(([json, total]) => total > 1 && json.length > MINIMUM_SHARED_LENGTH)
    .map(([json]) => json)
    .sort((a, b) => a.length - b.length || (a < b ? -1 : a > b ? 1 : 0));
  const ids = new Map(shared.map((json, index) => [json, index]));
  const encode = (node, root) => {
    if (!node || typeof node !== 'object') return node;
    const id = root ? undefined : ids.get(JSON.stringify(node));
    if (id !== undefined) return { [REFERENCE]: id };
    if (Array.isArray(node)) return node.map((child) => encode(child, false));
    const entries = Object.entries(node).map(([key, child]) => [key, encode(child, false)]);
    return Object.fromEntries(entries);
  };
  const table = shared.map((json) => encode(JSON.parse(json), true));
  return JSON.stringify([table, encode(catalog, true)]);
}

/** Render encoded command data as a single-quoted TypeScript module. */
export function renderCommandDataModule(catalog) {
  const text = encodeCommandData(JSON.parse(JSON.stringify(catalog)))
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029');
  return [
    '// Generated by pnpm commands:generate. Do not edit.',
    '// Compact runtime form of COMMAND_SPECS; decode it with commandSpecs() from catalogue.ts.',
    `export const COMMAND_SPECS_DATA = '${text}';`,
    '',
  ].join('\n');
}
