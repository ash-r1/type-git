import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const registry = JSON.parse(await readFile(new URL('spec/git-string-callbacks.json', root), 'utf8'));
for (const [name, profile] of Object.entries(registry.profiles)) {
  if (!profile.source) throw new Error(`${name}: missing upstream evidence`);
  if (profile.kind === 'first-separator') {
    if (typeof profile.separator !== 'string' || profile.separator.length !== 1 || typeof profile.allowUnseparated !== 'boolean') throw new Error(`${name}: invalid first-separator grammar`);
  } else if (profile.kind === 'choice') {
    for (const field of ['exact', 'prefixes']) if (!Array.isArray(profile[field]) || profile[field].some(value => typeof value !== 'string' || !value)) throw new Error(`${name}: invalid ${field}`);
  } else throw new Error(`${name}: unknown string grammar`);
}
const source = `// Generated by node scripts/string-callbacks.mjs. Do not edit.\nimport type { StringCallbackProfile } from './string-callback.js';\nexport const STRING_CALLBACKS = ${JSON.stringify(registry.profiles, null, 2)} as const satisfies Record<string, StringCallbackProfile>;\n`;
const result = spawnSync(process.execPath, [require.resolve('@biomejs/biome/bin/biome'), 'format', '--stdin-file-path=src/constraints/string-callbacks.generated.ts'], { input: source, encoding: 'utf8' });
if (result.status !== 0) throw new Error(result.stderr);
const target = new URL('src/constraints/string-callbacks.generated.ts', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== result.stdout) throw new Error('String callback profiles are stale');
} else await writeFile(target, result.stdout);
